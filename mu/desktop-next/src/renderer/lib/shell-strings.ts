/** The table itself: exported so a test can require every language to carry every key. */
export const SHELL_TRANSLATIONS: Readonly<Record<ShellLanguage, ShellStrings>> = STRINGS;

export function shellText(language: string, key: string): string {
	const base = STRINGS[language as ShellLanguage] ?? STRINGS[language.split("-")[0] as ShellLanguage] ?? STRINGS.en;
	return base[key] ?? STRINGS.en[key] ?? key;
}
